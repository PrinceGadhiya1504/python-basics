# Variable is use to store data.
# Python variable do not require explicit declaration of type.
# It can store any type of data (int, float, string, etc.)

x = 10 
print(x, type(x))

x = "Hello"
print(x, type(x))

x = 10.5
print(x, type(x))

# Rules for naming variable names.
# 1. Variable name must start with a letter or underscore.
# 2. Variable name cannot start with a number.
# 3. Variable name can only contain alpha-numeric characters and underscores (A-z, 0-9, and _).
# 4. Variable names are case-sensitive (name, Name and NAME are different variables).
# 5. Variable names cannot be keywords.

# Valid variable names
my_variable = 10
myVariable = 20
my_variable_2 = 30
_my_variable = 40

# Invalid variable names
# 2my_variable = 10
# my-variable = 20
# my variable = 30
# my_variable@ = 40
