# Task: Countdown
    # 1. count = 5 variable banao.
    # 2. while loop chalao jab tak count zero se bada hai.
    # 3. Har iteration mein count print karo.
    # 4. Har iteration ke baad count ko 1 se decrease karo.
# Expected output:
    # 5
    # 4
    # 3
    # 2
    # 1

count = 5

while count > 0:
    print(count)
    count -= 1