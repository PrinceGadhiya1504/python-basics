# Task:
    # 1. calculate_square(number) naam ka function banao.
    # 2. Function ke andar square naam ka local variable banao, jisme number * number store ho.
    # 3. square ko return karo.
    # 4. Function ko 5 ke saath call karke result print karo.
# Expected output:
