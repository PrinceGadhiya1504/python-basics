# Task:
    # 1. calculate_total(numbers) naam ka function banao.
    # 2. Function ko ek list parameter milega.
    # 3. List ke sabhi numbers ka total calculate karke return karo.
    # 4. Function ko [10, 20, 30, 40] list ke saath call karo.
    # 5. Returned total ko print karo.
# Expected output:
    # 100

def calculate_total(numbers):
    return sum(numbers)
    
print(calculate_total([10, 20, 30, 40]))